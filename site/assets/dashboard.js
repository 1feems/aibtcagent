async function main() {
  try {
    const data = await loadDashboardData();

    if (page === "overview") {
      renderOverview(data);
      return;
    }

    if (page === "beats") {
      renderBeats(data);
      return;
    }

    if (page === "bounties") {
      renderBounties(data);
      return;
    }

    if (page === "briefs") {
      renderBriefs(data);
    }
  } catch (error) {
    const shell = document.querySelector(".shell");
    if (shell) {
      shell.innerHTML = `<section class="panel"><h1>Dashboard load failed</h1><p class="hero-text">${error.message}</p></section>`;
    }
  }
}

main();
